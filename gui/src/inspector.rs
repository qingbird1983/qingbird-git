//! 检视列：仓库页右侧那一列，可收起、可拉伸。**现在是一张空卡。**
//!
//! **这里不是官方 `Sheet`。** `Sheet` 是模态浮层——它带遮罩、会吃掉整个窗口的
//! 点击、并劫持 Esc 与焦点（`BaseSheet` + `focus_handle` + `overlay`）。设计文档第 1.1 节
//! 写的是"抽屉可收起，收起后内容区获得空间""收起不会丢失日志状态——它只是不可见"，
//! 这两条全都要求它是版面里的一列，不是盖在版面上的一层。
//! 官方 `Sheet` 留给真正需要"盖住界面"的地方：提交 diff。
//!
//! **2026-10-05：正文清空，标成「开发中」。** 原来这里有四个页签
//! （日志 / 变更 / 历史 / 空间），其中历史与空间和中栏的页签是**同一份数据、
//! 同一套内容**——两个入口看同一件事；变更升格成了中栏页签；日志整块搬去了
//! 中栏概览页的下半段。四个页签全撤之后这一列空了。
//!
//! **但模块留着**（用户口径："暂时保留右栏的模块，先标成开发中，我未来规划给 AI 用"）。
//!
//! **2026-10-09 这一轮把"留着的那三样"改成了两样**（用户的令）：
//! ① 外壳换成与左栏**同一颗** `widgets::card(t)` ——圆角 / 卡面白 / 1px 边 / `sh_2`
//!    阴影全部只有一个出处，不再是一整块 `popover` 底铺到窗口边；
//! ② 卡里**只留一句**「AI 助理面板 · 开发中」，原来的「检视」标题行、
//!    标题下那行仓库名、分隔线、以及占位里那两行说明小字**全部删掉**；
//! ③ 收起 / 展开那颗键**搬进顶栏**（`shell.rs::inspector_toggle`，紧挨明暗主题键），
//!    所以这一列里不再有任何可点的东西。
//! 仍然留着的两样：**列本身**（宽度、可收起、可拉伸）与**落盘的列宽设置**
//! （`store::Settings::inspector_w`）。将来往里放 AI 会话 / 提交建议 / 差异审阅时，
//! 这一列的骨架可以直接用；把列删掉将来要重建，重建时这两样又得重新做一遍。
//!
//! ⚠️ 卡里现在**一个可点的东西都没有**。往这一列加交互之前先回来看一句：
//! 它的外壳与左栏同源（`widgets::card`），左栏那套"行自己画、命中区铺到卡内缘"
//! 的经验不能照搬——这一列还没有行，也没有侧栏那种三层锁步的气口。

use gpui_kit::base::v_flex;
use gpui_kit::component::Theme;
use gpui_kit::{div, px, Context, Div, FontWeight, ParentElement, Styled};

use crate::state::*;
use crate::tokens::*;

// ================= 检视列（右侧常驻那一列） =================

impl Shell {
    /// 右侧那一列：一张与左栏同款的悬浮空卡，中间一句「开发中」。
    ///
    /// **不自己设宽度**：这一列是 `shell.rs` 里 `h_resizable("insp-split")`
    /// 的第 1 号面板，宽度由 `ResizableState` 派给 `flex_basis`，
    /// 自己再写一个 `w(px(..))` 会和它打架（每帧以谁为准说不清）。
    /// `self.inspector_w` 只在**首次挂上**、状态里还没有它那一格时当初值用
    pub(crate) fn inspector(&self, t: &Theme, _cx: &mut Context<Self>) -> Div {
        // **就是左栏那一颗外壳**（`sidebar::side_shell`），不是"照它再画一张"：
        // 圆角 / 卡面白 / 1px 边 / `sh_2` / 内距 / 顶边距 / 朝向中间列的气口
        // 六个属性全部只有一个出处。用户这一条要的是"与左栏一样"，
        // 而"一样"在代码里的形态只能是**同一个函数**
        crate::sidebar::side_shell(t, crate::sidebar::Facing::Right)
            .child(self.inspector_placeholder(t))
    }

    /// 卡里唯一那句占位。**只有一行**——用户 2026-10-09 的令是
    /// 「其它文字全部清除」，所以原来官方 `Empty` 那三层（标题 + 两行说明）
    /// 收成一句居中文案，`Empty` 也随之撤掉（留一层壳只会让人以为还有层级要填）
    fn inspector_placeholder(&self, t: &Theme) -> Div {
        v_flex()
            .flex_1()
            .min_h_0()
            .items_center()
            .justify_center()
            .child(
                div()
                    .text_size(px(fs_sec()))
                    .font_weight(FontWeight::MEDIUM)
                    .text_color(tier3(t))
                    .child("AI 助理面板 · 开发中"),
            )
    }
}
