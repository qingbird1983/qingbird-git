    /// **回弹必须看得见**——这条钉的是"过冲量落在人眼能分辨的区间里"。
    ///
    /// 为什么要有它：2026-10-05 报的「侧栏滑出后没有回弹效果」，根因就是
    /// 阻尼 0.85 ⇒ 过冲 0.63% ⇒ 220px 行程上只有 **1.4px**，算得出、看不见。
    /// 那种缺陷 `cargo check` 零错、单测全绿、弹簧也确实在跑，
    /// **任何以"有没有报错 / 有没有在动"为判据的自查都拦不住它**——
    /// 只能把"过冲量本身"写成一条可计算的断言。
    ///
    /// 下界 5%：低于它就是"动效在跑但用户感觉不到回弹"（= 这次报的那个 bug）。
    /// 上界 15%：高于它在大位移上会晃，而且小位移场合（几像素）会变成抖动。
    #[test]
    fn the_bounce_tier_overshoots_enough_to_be_seen() {
        // 欠阻尼弹簧第一次过冲量 / 行程 = exp(-πζ / √(1-ζ²))
        let z = SPRING_BOUNCE_DAMPING;
        assert!(
            (0.0..1.0).contains(&z),
            "ζ={z} 不在欠阻尼区，没有过冲可言——这一档就白配了"
        );
        let ratio = (-std::f64::consts::PI * z as f64 / (1.0 - z as f64 * z as f64).sqrt()).exp();

        assert!(
            ratio >= 0.05,
            "过冲只有 {:.2}%：侧栏 220px 行程上不到 11px，用户看不出「弹了一下」。\
             这正是 2026-10-05 报的「没有回弹效果」（当时 ζ=0.85 ⇒ 0.63%）。\
             调低 {SPRING_BOUNCE_DAMPING} 的阻尼。",
            ratio * 100.0
        );
        assert!(
            ratio <= 0.15,
            "过冲 {:.2}% 过大：侧栏这种大位移上会晃，小位移场合更会变成抖动。\
             调高 {SPRING_BOUNCE_DAMPING} 的阻尼。",
            ratio * 100.0
        );
    }

    /// 响应周期是"被感知的快慢尺度"，太慢侧栏开合会发黏。
    /// 这条不是审美，是上界：官方 `spring_move` 的 280ms 配 0.6 阻尼
    /// 要 600ms 以上才稳，那已经是"界面卡了一下"而不是"弹了一下"。
    #[test]
    fn the_bounce_tier_settles_before_it_feels_stuck() {
        assert!(
            (120..=240).contains(&SPRING_BOUNCE_RESPONSE_MS),
            "响应周期 {}ms：低于 120 会像被弹了一下就断，高于 240 在 \
             0.6 阻尼下要 600ms+ 才稳，侧栏开合会发黏",
            SPRING_BOUNCE_RESPONSE_MS
        );
    }
