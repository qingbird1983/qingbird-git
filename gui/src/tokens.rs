// ---------- 版面规范：字号 / 圆角 / 间距 / 按钮 / 图标 ----------
// 之前这些值是就地硬编码，结果同一个「卡片圆角」在不同屏上冒出
// 1/2/3/5/10 五种杂值，按钮高度有 6 种。这里定成档位，新增元素只能选档，
// 不许再写裸数字——视觉一致靠的是只有这几档可挑。

// ================= 字体三档（阶段 21-8，用户拍板） =================
//
// **这一组不是「又加了几个字号」，是给已有的六档定语义。**
// 动手前的实测（逐文件 grep -c 统计）：
//
// | 档位 | 值 | 用了多少次 |
// |---|---:|---:|
// | `FS_META` | 11 | **68** |
// | `FS_SEC`  | 12 | **52** |
// | `FS_BODY` | 13 | **17** |
// | `FS_TITLE`| 16 | 2 |
// | `FS_HEAD` | 18 | 4 |
// | `FS_NUM`  | 20 | 4 |
//
// **症结不是档位太多，是「该当正文的内容被当成元信息在用」**：
// 11px 是绝对主力、13px 只有 17 次。所以这一档的规范是**收编**——
// 逐处判断 68 处里哪些其实是正文，是正文的升到 13px，而不是新增第四档。
//
// ## 三档的语义（**字号与明暗度要配对**，别混着用）
//
// | 层级 | 字号 | 明暗度 | 用在哪 |
// |---|---|---|---|
// | **一级** | `FS_TITLE` 16 / `FS_HEAD` 18 | `foreground` | 页面主标题、弹窗与卡标题 |
// | **二级** | `FS_BODY` 13 | `body(t)` | **正文**：仓库名、设置里的段标题、提交标题 |
// | **三级** | `FS_SEC` 12 / `FS_META` 11 | `tier3(t)` / `tier4(t)` | 元信息、时间戳、说明、占位 |
//
// ⚠️ **最常见的错是拿 11px 配 `body(t)`**：最小字号却给正文色，
// 读起来像「被缩小的正文」，而它本该是元信息。带 cargo test 的
// `font_sizes_stay_ordered` 盯住档位本身，这条配对靠人读上下文判。
//
// ⚠️ **等宽小字是例外**：`fork.rs` 里的 commit hash 用
// `FS_META` + `body(t)` 是对的——技术标识符就该小而清晰，
// 与「正文」不是一回事。
//
// ================= 阶段 28：字号放大 + 运行期三档 =================
//
// **2026-10-06 用户报「整个界面的文字都太小了」。** 重测一遍用量，数字更难看：
//
// | 档位 | 阶段 21 的值 | 阶段 28 重测用量 |
// |---|---:|---:|
// | `FS_META` | 11 | **77** |
// | `FS_SEC`  | 12 | **58** |
// | `FS_BODY` | 13 | 26 |
// | `FS_TITLE`| 16 | 6 |
// | `FS_HEAD` | 18 | 8 |
// | `FS_NUM`  | 20 | 7 |
//
// **182 处文字里 135 处（74%）挤在最小的两档。** 更要命的是 11/12/13
// **只差 1px**——这个步进肉眼分不出来，所以「三级」读起来就是
// 「小一号的正文」而不是一个层级，文件头那句「11px 配 body(t) 读起来
// 像被缩小的正文」说的正是这件事。
//
// ⇒ 用户拍板新字阶 **12/14/16/19/22/26**：**底部三档的步进从 1px 变成
// 2px**——层级要能被看见，步进得先能被看见；顶部同时拉开，
// 页面标题与卡片标题才真的分得开。
//
// ## 为什么三档各自是「六档全套整数」而不是「一套值 × 一个系数」
//
// 用系数会在小数上飘，而**层级恰恰靠「底部三档差 2px」这条不变式成立**
// ——系数一乘，`12×0.9=10.8` 与 `14×0.9=12.6` 差 1.8，
// 读起来又回到"分不出层级"。所以每档都是一组**挑过的整数**，
// 并由 `UiScale::step_invariant` 在单测里把「底部三档两两差 ≥ 2px」
// 钉死——**三档都要满足**，不是只验中档。

/// 界面字号档位。设置里的「界面字号」就是它
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub(crate) enum UiScale {
    Small,
    #[default]
    Medium,
    Large,
}

/// 一档里所有「要跟着字号走」的量。**字号与控件高度必须一起动**——
/// 只放大字号不放高胶囊，11px 的胶囊塞 13px 的字会被切
#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) struct Metrics {
    pub meta: f32,
    pub sec: f32,
    pub body: f32,
    pub title: f32,
    pub head: f32,
    pub num: f32,
    /// 胶囊高度（徽章 / 状态药丸）
    pub pill_h: f32,
    /// 标题栏高度
    pub title_bar_h: f32,
}

impl UiScale {
    /// 三档各自的全部量。**纯函数**——单测只碰它，不碰运行期载体，
    /// 免得像 `diag` 那次在并行跑的用例之间互踩（`AGENTS.md` 记着）
    pub(crate) const fn metrics(self) -> Metrics {
        match self {
            //          meta sec body title head num  pill 标题栏
            // ⚠️ `pill` 那一列 2026-10-08 从 24/28/32 降到 **22/24/28**：
            // 原型 `.pill { height: 24px; font-size: 11.5px }` ⇒ 比值 2.09，
            // 而我们中档字是 `fs_meta`=12 ⇒ 24 正好是同一个比值。
            // 原来 28 装 12 的字是 2.33 倍，胶囊比它的字重一档，
            // 塞进 30 高的表格行里就成了"胶囊比行距还大"（用户 2026-10-08 挑的）
            UiScale::Small => Metrics {
                meta: 11.0,
                sec: 13.0,
                body: 15.0,
                title: 18.0,
                head: 21.0,
                num: 24.0,
                pill_h: 22.0,
                title_bar_h: 36.0,
            },
            UiScale::Medium => Metrics {
                meta: 12.0,
                sec: 14.0,
                body: 16.0,
                title: 19.0,
                head: 22.0,
                num: 26.0,
                pill_h: 24.0,
                title_bar_h: 40.0,
            },
            UiScale::Large => Metrics {
                meta: 14.0,
                sec: 16.0,
                body: 18.0,
                title: 22.0,
                head: 26.0,
                num: 30.0,
                pill_h: 28.0,
                title_bar_h: 44.0,
            },
        }
    }

    /// 官方组件（Button / Input）的基准字号。
    ///
    /// **取 `body` 那一档而不是另定一个数**：官方件是我们版面的"普通文字"，
    /// 它的字号理应与我们的正文同档。基座自带的 `font_size` 是全局量，
    /// 改它一处就够——不必去逐个组件覆写。
    pub(crate) fn base_font(self) -> f32 {
        self.metrics().body
    }

    /// 设置里存的是字符串。**认不出一律落中档**，同 `theme.rs` 对配色名的处理：
    /// 认不出来时"静默取一个看着差不多的"比"落回默认值并说明"更容易让人以为生效了
    pub(crate) fn from_stored(s: &str) -> Self {
        match s.trim() {
            "small" => UiScale::Small,
            "large" => UiScale::Large,
            _ => UiScale::Medium,
        }
    }

    pub(crate) const fn stored(self) -> &'static str {
        match self {
            UiScale::Small => "small",
            UiScale::Medium => "medium",
            UiScale::Large => "large",
        }
    }

    /// 设置页上那颗控件的三颗键
    pub(crate) const ALL: [UiScale; 3] = [UiScale::Small, UiScale::Medium, UiScale::Large];

    pub(crate) const fn label(self) -> &'static str {
        match self {
            UiScale::Small => "小",
            UiScale::Medium => "中",
            UiScale::Large => "大",
        }
    }

    /// 附一句当前字号，让设置页那颗控件不用猜自己选中了什么
    pub(crate) fn note(self) -> String {
        let m = self.metrics();
        format!("正文 {}px · 弱提示 {}px", m.body as i32, m.meta as i32)
    }
}

/// 运行期载体。**只有 `set_ui_scale` 写它，渲染路径只读**
///
/// 用 `AtomicU8` 而不是 `Mutex<f32>`：182 处每帧各读一次，
/// 读路径必须是一条 relaxed load，不能有锁也不能有分配。
static SCALE: std::sync::atomic::AtomicU8 = std::sync::atomic::AtomicU8::new(1);

/// 切档。**启动时读一次、设置里改时调一次**，渲染路径不调
///
/// ⚠️ **这里刻意不写 `diag::note`**：这一行每次启动都会走，写进去就是
/// 每次启动给用户的 `app.log` 添一行垃圾（阶段 25 记着这个代价）。
/// **该记的是"用户自己拨了"那一刻**，那条在 `Shell::set_ui_scale_static`
/// 里——它才是可行动的信息，而"当前是第几档"用户自己能在设置里看见。
pub(crate) fn set_ui_scale(s: UiScale) {
    let v = match s {
        UiScale::Small => 0u8,
        UiScale::Medium => 1,
        UiScale::Large => 2,
    };
    SCALE.store(v, std::sync::atomic::Ordering::Relaxed);
}

/// 当前档的全部量。**每帧被调 182 次**（每个 `fs_*()` 一次）
