/// 29.5 vs 轨中心 35.5，差 6px，肉眼一眼能看出来"没对齐"。）
pub(crate) const TITLE_BAR_PAD_L: f32 = NAV_W / 2.0 - APP_ICON / 2.0;

/// 窗口控件（最小化 / 最大化 / 关闭）单键的边长。
///
/// 官方 `ControlIcon` 是**私有 enum**（`title_bar.rs:111`），导不出来复用，
