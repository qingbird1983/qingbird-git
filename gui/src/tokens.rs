/// 那一套就接不上了
pub(crate) const TITLE_BAR_CTRL_W: f32 = 34.0;

// ---------- 动效档（阶段 25）----------
//
// ⚠️ **官方那两条弹簧档都看不见回弹，这不是配置没调，是阻尼比决定的。**
// 欠阻尼弹簧的第一次过冲量 ≈ 行程的 `exp(-πζ / √(1-ζ²))`：
//
// | 档 | ζ | 过冲比例 | 220px 行程上的实际过冲 |
// |---|---|---|---|
// | 官方 `spring_control` | **1.00**（`Spring::new` 的默认，没被覆写） | 0% | 0px，压根不过冲 |
// | 官方 `spring_move` | 0.85 | 0.63% | **1.4px**——算得出，肉眼看不见 |
// | `SPRING_BOUNCE_DAMPING` | 0.60 | 9.5% | **21px**——一眼看得出「到位后弹一下」|
//
// 2026-10-05 实机反馈「侧栏滑出后没有回弹效果」，查下来就是这一条：
// 代码确实走了 `spring_move`、弹簧也确实在跑，只是 1.4px 谁都看不见。
// **判据：位移越大越要低阻尼**——大位移配高阻尼等于白配一根弹簧。
// 小位移（几像素的悬停/按下）反过来必须用高阻尼：0.6 阻尼下 4px 的过冲
// 会变成"抖了一下"，那种才叫难受。

/// 回弹档的阻尼比。0.6 ⇒ 约 9.5% 过冲。低于 0.5 会开始"晃"，别再往下调。
pub(crate) const SPRING_BOUNCE_DAMPING: f32 = 0.60;
/// 回弹档的响应周期。**不是时长**：它是无阻尼时一次完整往返的周期，
/// 也就是"这个动效被感知到的快慢尺度"。200ms ⇒ 稳定下来约 450ms。
/// 官方 `spring_move` 的 280ms 配 0.6 阻尼会拖到 600ms 以上，侧栏开合显得黏。
pub(crate) const SPRING_BOUNCE_RESPONSE_MS: u64 = 200;
/// 收敛容差，单位与被动画的值一致（这里是像素）。0.1px 与官方同档。
const SPRING_EPSILON: f32 = 0.1;

/// **到位后过冲再收住**——用于大位移：侧栏滑入/滑出、检视抽屉。
///
/// 官方两条档都不带可见回弹（见上面那张表），所以这一档是自订的。
/// 想要"稳稳停住不要过冲"就用官方 `spring_move`，别拿这一档去代替它。
pub(crate) fn spring_bounce() -> gpui_kit::base::motion::Spring {
    gpui_kit::base::motion::Spring::new(std::time::Duration::from_millis(
        SPRING_BOUNCE_RESPONSE_MS,
    ))
    .with_damping(SPRING_BOUNCE_DAMPING)
    .with_epsilon(SPRING_EPSILON)
}

/// 行内图标（统一走 lucide 一套，只有品牌 logo 用 assets 的 Bird）。
/// 尺寸显式写死而不是 `.small()`：两套图标集混着用时，默认尺寸并不一致，
/// 显式档位才能保证行与行对齐。
pub(crate) fn icon_sm(name: impl Into<Icon>) -> Icon {
    Icon::new(name).with_size(Size::Size(px(ICON_SM)))
}

/// 按钮内图标
pub(crate) fn icon_md(name: impl Into<Icon>) -> Icon {
    Icon::new(name).with_size(Size::Size(px(ICON)))
}

/// 图标底块里的图标（20px，`GLYPH_ICON` 那一档）。
///
/// ⚠️ 这里的 `Size::Size(px(..))` **不是** AGENTS 禁写的那一条：禁的是**官方 `Button`**
/// 的自定义 px 档（它会联动把文字放大到 16px、图标 size×0.75）。
/// `Icon` 自己的 `with_size` 就是字面尺寸，且 `.icon(icon_md(..))` 传进 Button 时
/// 尺寸会被无条件丢弃（`button.rs:756-761`）——所以这一档**只能直接放进容器**，
/// 不能指望它穿过 Button 生效。
pub(crate) fn icon_box(name: impl Into<Icon>) -> Icon {
    Icon::new(name).with_size(Size::Size(px(GLYPH_ICON)))
}

