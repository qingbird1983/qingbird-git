/// **行高系数：1.7。`row_h()` 与 `line_height(DefiniteLength::Fraction(LH_ROW))` 共用这一个数。**
///
/// 为什么要有这个名字：这两条路是**同一个量的两个出口**——`row_h` 算的是"一行占多高"
/// 给需要显式外框的地方（图标+文字并排那种行），`line_height` 设的是文本自己的行盒。
/// 各写一个 1.7 就是"同一属性两个出处"（机器闸 R1 那一类），迟早漂成行盒 1.7、外框 1.9。
pub(crate) const LH_ROW: f32 = 1.7;
/// **纯文字页头**（标题 + 副标题竖着叠两行）的行盒系数：**1.25**。
///
/// `LH_ROW` 那 1.7 是为「行里要坐得下一颗 24 的控件」准备的，页头两行里
/// 一颗控件都没有，1.7 的余量就全变成空白：2026-10-08 在总览页帧上逐行量，
/// 「总览」(22px) 行盒 37.4 而**墨迹只有 21**（y=43..63），副标题 (14px)
/// 行盒 23.8 而墨迹 12（y=78..89），两行连上下气口一共占掉 **70px**，
/// 第一张统计卡被顶到 y=104。
/// ⇒ 中文墨迹 ≈ 0.95 × 字号（上面那两个数就是这么来的），1.25 留下
/// 0.30 个字号的余量（21px 档 5.25px、13px 档 3.9px）——呼吸还在，空白没了。
/// 页头整块从 70 收到 **60**（`overview.rs::ov_head` 里还补了 4 给对齐基线，
/// 见 `NAV_PAD_TOP`），第一张统计卡的顶边从 y=104 提到 **y=94**，
/// 省下的 10px 全部落到下面那张 `flex_1` 的表格里
/// （用户 2026-10-08 第 ④ 条：「页面内容要考虑最大化利用」）。
///
/// ⚠️ **系数而不是像素**：字号是三档可切的，写死一个行高会在大档切字。
/// 与 `num_row_h`(1.2) 的差别只在出口：那一档撑的是 div 外框，
/// 这一档走 `.line_height()`（gpui 原文 "of this element **and its children**"，
/// 所以设在页头那一列上，两行连同里面的每一段都跟上）
///
/// ⚠️ **名字里的"页头"不是限制**（2026-10-09 起了第二个用处：空间页
/// 「构建缓存 / `.gitignore` 建议」那两段的**名字 + 一句解释**也用它）。
/// 判据是「一个块里竖着叠两行**纯文字**、行里没有控件」——满足就用这一档。
/// 这条纪律是 AGENTS 里那条「给一个档起名字时别把用途写死，否则第二个用途
/// 来了会另起一个名字」的直接兑现：这一处若另起一个 `LH_ROW_LINE = 1.25`，
/// 就是同一个属性两个出处
pub(crate) const LH_HEAD: f32 = 1.25;
/// 一行「图标 + 文字（+ 右侧小按钮）」的行高。**由字号派生，不许写死**。
///
/// **为什么必须是函数而不是常量**（阶段 28）：三档字号差了 2~4px，
/// 写死的那一行从中档就开始贴边、到大档必切。而"切字"这种缺陷
/// `cargo check` 零错、单测全绿、**抓帧看着也只是"有点挤"**——
/// 它不会以任何形式报错，只能靠把行高写成字号的函数来保证它不可能发生。
///
/// ⚠️ **纯文本那一行不要用 `.h(px(row_h(..)))`，要用 `.line_height(Fraction(LH_ROW))`**：
/// 撑 div 外框不会把文字居中，gpui 的文本按基线画、会在框里**沉底**
/// （2026-10-08 实测：37.4 的框里 25 高的墨迹偏下 6.3px，整屏"上缩进"因此虚高 13px）。
/// `row_h` 留给"行里要坐得下一颗控件"的那种行——那种行的高度本来就是外框说了算
pub(crate) fn row_h(text_px: f32) -> f32 {
    text_px * LH_ROW
}
/// **数字与标签竖着叠一列**时每一行的行高（统计卡那一列）。
///
/// `row_h` 的 1.9 倍就是 gpui 给一行字的**自然**行高（实测：26px 的数字撑出 49、
/// 12px 的标签撑出 23）。那一档是为「图标 + 文字**并排**」的一行准备的——
/// 行里要坐得下一颗 24 的控件，所以留得松。
/// ⚠️ 但**竖着叠两行**时这个松是要还的：49 + `GAP_DENSE` 2 + 23 = 74 的一列
/// 把统计卡撑到 **98** 高（2026-10-07 抓帧实测），比改之前那版
/// 「数字靠左 + 标签被 `flex_1` 推到最右」的 73 还高出 25px，
/// 而且字号档越大越荒谬。⇒ 这一列里两行都按 **1.2 倍**给：
/// 数字的墨迹只有字号的 0.9 倍高，1.2 倍留得出气口、又不把卡撑开
/// （原型 `.stat .num` 的 line-height 是 1.05，我们取 1.2 是因为中文标签
/// 的字面比拉丁数字高）
pub(crate) fn num_row_h(text_px: f32) -> f32 {
    text_px * 1.2
}
