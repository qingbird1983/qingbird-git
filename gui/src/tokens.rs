/// 自研标题栏时这一档只能自己定，**但对齐官方那个值**（34）：
/// Windows 的窗口控件命中区是系统约定的固定宽度，跟着官方的走，
/// 换成一个"我觉得合适"的数只会让这块和系统其余窗口不一致。
///
/// ⚠️ 这三个键**只声明 `window_control_area`，不自己处理点击**（见
